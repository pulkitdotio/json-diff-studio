import { expect, test } from '@playwright/test'

test('compares the example, filters, inspects values, and stays within the viewport', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('See exactly what changed.')
  await expect(page.getByRole('button', { name: /Compare JSON/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await expect(page.getByLabel('Difference statistics')).toContainText('9Total changes')
  await page.getByRole('button', { name: 'Added 3', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('"timeout"')
  await expect(page.getByRole('table')).not.toContainText('"deprecated"')
  await page.getByRole('button', { name: 'All changes 9', exact: true }).click()
  await page.getByRole('button', { name: '"port"', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('/server/port')
  await expect(page.getByRole('dialog')).toContainText('8080')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: '"port"', exact: true })).toBeFocused()
  await page.getByRole('checkbox', { name: 'Show unchanged' }).check()
  await expect(page.getByRole('table')).toContainText('"environment"')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  expect(errors).toEqual([])
  if (process.env.CAPTURE_SCREENSHOTS) {
    await page.getByRole('checkbox', { name: 'Show unchanged' }).uncheck()
    const dismiss = page.getByRole('button', { name: 'Dismiss notification' })
    if (await dismiss.isVisible()) await dismiss.click()
    await page.evaluate(() => {
      if (document.activeElement instanceof HTMLElement) document.activeElement.blur()
      document.querySelector('.diff-table-scroll')?.scrollTo(0, 0)
      window.scrollTo(0, 0)
    })
    await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-dark.png`, fullPage: true })
    await page.getByRole('button', { name: 'Switch to light theme' }).click()
    await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-light.png`, fullPage: true })
  }
})

test('validates, formats, marks stale results, compares with keyboard, and restores cleared inputs', async ({ page }) => {
  await page.goto('/')
  const original = page.getByRole('textbox', { name: 'Original JSON' })
  const modified = page.getByRole('textbox', { name: 'Modified JSON' })
  await original.fill('{"value":1}')
  await modified.fill('{bad}')
  await expect(modified).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('button', { name: /Compare JSON/ })).toBeDisabled()
  await modified.fill('{"value":2}')
  await page.getByRole('button', { name: 'Format Modified JSON' }).click()
  await expect(modified).toHaveValue('{\n  "value": 2\n}')
  await page.getByRole('button', { name: /Compare JSON/ }).click()
  await expect(page.getByLabel('Difference statistics')).toContainText('1Total changes')
  await modified.fill('{"value":1}')
  await expect(page.getByText(/Inputs have changed/)).toBeVisible()
  await modified.press('Control+Enter')
  await expect(page.getByText('Perfect match.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear both' }).click()
  await expect(original).toHaveValue('')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(original).toHaveValue('{"value":1}')
})

test('uploads locally, rejects large files, and makes no external processing requests', async ({ page }) => {
  const external: string[] = []
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:5173/') && !request.url().startsWith('ws://127.0.0.1:5173/')) external.push(request.url()) })
  await page.goto('/')
  await page.getByLabel('Original JSON file').setInputFiles({ name: 'before.json', mimeType: 'application/json', buffer: Buffer.from('{"private":"synthetic"}') })
  await expect(page.getByRole('textbox', { name: 'Original JSON' })).toHaveValue('{"private":"synthetic"}')
  await page.getByLabel('Modified JSON file').setInputFiles({ name: 'after.json', mimeType: 'application/json', buffer: Buffer.from('{"private":"changed"}') })
  await page.getByRole('button', { name: /Compare JSON/ }).click()
  await expect(page.getByRole('table')).toContainText('"changed"')
  await page.getByLabel('Original JSON file').setInputFiles({ name: 'large.json', mimeType: 'application/json', buffer: Buffer.alloc(1024 * 1024 + 1, ' ') })
  await expect(page.getByRole('alert')).toContainText('1 MiB')
  await expect(page.getByRole('textbox', { name: 'Original JSON' })).toHaveValue('{"private":"synthetic"}')
  expect(external).toEqual([])
})

test('copies a structured diff through the real Clipboard API', async ({ page, context, browserName }) => {
  test.skip(browserName !== 'chromium', 'Clipboard permissions tested in Chromium.')
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await page.getByRole('button', { name: 'Copy report', exact: true }).click()
  await expect(page.getByText('Diff report copied to clipboard.')).toBeVisible()
  const report = await page.evaluate(async () => JSON.parse(await navigator.clipboard.readText()) as { counts: { total: number } })
  expect(report.counts.total).toBe(9)
})
